#!/usr/bin/env bash
# Build dist/install-eduka-update-system-cubic.sh from this checkout: one
# self-contained script (installer, data files and the release binaries are
# embedded as an xz archive) for ISO work in Cubic when neither the
# repository nor the .deb is copied into the chroot. Build the binaries
# first (make build). SPDX-License-Identifier: GPL-3.0-or-later
set -Eeuo pipefail

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
OUTPUT="${1:-$PROJECT_DIR/dist/install-eduka-update-system-cubic.sh}"
VERSION="$(tr -d '[:space:]' <"$PROJECT_DIR/VERSION")"
BIN_DIR="${EUS_BIN_DIR:-$PROJECT_DIR/target/release}"
PROGRAMS=(eduka-update-system-gui eduka-update-system-tool eus-panel-status eus-tray-indicator)
for program in "${PROGRAMS[@]}"; do
    [[ -x "$BIN_DIR/$program" ]] || { printf 'Missing %s; run make build first.\n' "$BIN_DIR/$program" >&2; exit 69; }
done
mkdir -p -- "$(dirname -- "$OUTPUT")"
STAGE="$(mktemp -d -t eus-cubic-build.XXXXXXXX)"
trap 'rm -rf -- "$STAGE"' EXIT
install -d "$STAGE/bin"
for program in "${PROGRAMS[@]}"; do
    install -m 0755 "$BIN_DIR/$program" "$STAGE/bin/$program"
done

{
    cat <<HEADER
#!/bin/bash
# Eduka-Update-System (EUS) ${VERSION} self-contained installer for Edukasaun OS / Debian ($(dpkg --print-architecture 2>/dev/null || uname -m)).
# Generated by tools/build-cubic-installer.sh - do not edit by hand.
#
# Inside the Cubic terminal (chroot), as root:
#   bash install-eduka-update-system-cubic.sh            # installs missing dependencies too
#   bash install-eduka-update-system-cubic.sh --no-deps  # files only
# Test without touching the system:
#   EUS_INSTALL_ROOT=/tmp/eus-root bash install-eduka-update-system-cubic.sh
set -Eeuo pipefail

EUS_VERSION='${VERSION}'
HEADER
    cat <<'BODY'
WORK_DIR="$(mktemp -d -t eus-cubic.XXXXXXXX)"
trap 'rm -rf -- "$WORK_DIR"' EXIT

if [[ -z "${EUS_INSTALL_ROOT:-}" && "${EUID:-$(id -u)}" -ne 0 ]]; then
    echo "ERROR: Run this installer as root (sudo bash $0)." >&2
    exit 1
fi

echo "Installing Eduka-Update-System ${EUS_VERSION}..."
sed -n '/^__EUS_ARCHIVE_BELOW__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xJ -C "$WORK_DIR"
bin_dir="$WORK_DIR/eduka-update-system/bin"
if [[ -n "${EUS_INSTALL_ROOT:-}" ]]; then
    bash "$WORK_DIR/eduka-update-system/install.sh" --bindir "$bin_dir" --destdir "$EUS_INSTALL_ROOT" "$@"
else
    bash "$WORK_DIR/eduka-update-system/install.sh" --bindir "$bin_dir" "$@"
fi
exit 0
__EUS_ARCHIVE_BELOW__
BODY
    tar --transform 's,^\.,eduka-update-system,' --owner=0 --group=0 --sort=name -cJf - \
        -C "$PROJECT_DIR" ./install.sh ./uninstall.sh ./VERSION ./LICENSE ./requirements-system.txt \
        ./src ./data ./assets ./config -C "$STAGE" ./bin | base64 -w 76
} >"$OUTPUT.tmp"
chmod 0755 "$OUTPUT.tmp"
mv -f -- "$OUTPUT.tmp" "$OUTPUT"
printf '%s\n' "$OUTPUT"
